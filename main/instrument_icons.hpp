// Full opaque frame, packed high-nibble first for M5GFX's 4-bit palette.
// Only 8 KiB of persistent RAM; rendering uses no heap or task-stack image.
inline constexpr size_t kFrameBytes = 128 * 128 / 2;
inline void compose(int icon, uint8_t (&frame)[kFrameBytes]) {
    if (icon < 0 || icon > kFault) icon = kFault;
    for (int y = 0; y < 128; ++y) {
        for (int x = 0; x < 128; x += 2) {
            const char pixel = kArt[icon][y / 4][x / 4];
            const uint8_t color = pixel == '#' ? 1 : pixel == 'R' ? 2 : 0;
            frame[(y * 128 + x) / 2] = color * 0x11;
        }
    }
}
